// Generates the one-time Supabase setup files from the migrations and seed data, so they never drift apart:
//   supabase/setup.sql            → paste into Supabase → SQL Editor → Run (once)
//   supabase/sample-products.sql  → OPTIONAL: the 12 illustrated sample products
// Run: npm run db:build-sql
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { categories, coupons, seedProducts } from '../../src/data/products'
import { defaultSettings } from '../lib/settings'
import { STORAGE_ALLOWED_TYPES, STORAGE_MAX_BYTES } from '../lib/storage-rules'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const migDir = join(root, 'server', 'db', 'migrations')
const lit = (v: unknown): string => {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v === 'number') return String(v)
  if (typeof v === 'boolean') return v ? 'TRUE' : 'FALSE'
  if (Array.isArray(v)) return v.length ? `ARRAY[${v.map(lit).join(', ')}]::text[]` : `'{}'::text[]`
  if (typeof v === 'object') return `${lit(JSON.stringify(v))}::jsonb`
  return `'${String(v).replace(/'/g, "''")}'`
}

const EXPECTED_TABLES = ['addresses', 'admin_users', 'categories', 'coupons', 'inventory', 'order_items', 'order_status_history', 'orders', 'password_resets', 'product_images', 'product_variants', 'products', 'rate_limits', 'schema_migrations', 'sessions', 'site_settings', 'users', 'wishlist']
const migrations = readdirSync(migDir).filter((f) => f.endsWith('.sql')).sort()
const parts: string[] = [
  `-- ═══════════════════════════════════════════════════════════════════
-- Sirnaaz by Mehar — Supabase setup
-- Supabase dashboard → SQL Editor → New query → paste this whole file → Run.
--
-- SAFE TO RUN MORE THAN ONCE. Every table, index and setting is created only if it is missing,
-- and nothing that already exists is deleted or overwritten (your products, orders and settings are kept).
-- It runs as ONE transaction: if anything fails, nothing at all is changed.
-- The last result table shows a check list — every row should say OK.
-- Generated by \`npm run db:build-sql\` — do not edit by hand.
-- ═══════════════════════════════════════════════════════════════════
BEGIN;

CREATE TABLE IF NOT EXISTS schema_migrations (name TEXT PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now());
`,
]
for (const m of migrations) {
  parts.push(`-- ───────── migration ${m} ─────────\n${readFileSync(join(migDir, m), 'utf8').trim()}\nINSERT INTO schema_migrations (name) VALUES (${lit(m)}) ON CONFLICT (name) DO NOTHING;\n`)
}

parts.push(`-- ───────── store data: categories, coupons, settings ─────────
${categories.map((c, i) => `INSERT INTO categories (slug, name, tagline, sort_order) VALUES (${lit(c.slug)}, ${lit(c.name)}, ${lit(c.tagline)}, ${i}) ON CONFLICT (slug) DO NOTHING;`).join('\n')}
${coupons.map((c) => `INSERT INTO coupons (code, description, type, value, min_subtotal) VALUES (${lit(c.code)}, ${lit(c.description)}, ${lit(c.type)}, ${c.value}, ${c.minSubtotal}) ON CONFLICT (code) DO NOTHING;`).join('\n')}
INSERT INTO site_settings (id, data) VALUES (1, ${lit(defaultSettings)}) ON CONFLICT (id) DO NOTHING;
`)

parts.push(`-- ───────── product photo bucket ─────────
-- Public READ (shoppers must see photos). No upload/delete policies are created, so the only way to add or
-- remove a file is a short-lived signed upload link issued by the website's server to a signed-in admin, or the
-- server itself using the service-role key. Only JPEG/PNG/WebP up to ${STORAGE_MAX_BYTES / 1024 / 1024} MB are accepted (no SVG/HTML).
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('product-images', 'product-images', TRUE, ${STORAGE_MAX_BYTES}, ${lit([...STORAGE_ALLOWED_TYPES])})
ON CONFLICT (id) DO UPDATE SET public = EXCLUDED.public, file_size_limit = EXCLUDED.file_size_limit, allowed_mime_types = EXCLUDED.allowed_mime_types;

COMMIT;

-- ───────── check list: every row should say OK ─────────
WITH expected(t) AS (VALUES ${EXPECTED_TABLES.map((t) => `('${t}')`).join(', ')}),
cols(t, c) AS (VALUES ('orders', 'idempotency_key'), ('product_images', 'thumb_url'), ('product_images', 'thumb_key'))
SELECT * FROM (
  SELECT 1 AS n, 'All ' || (SELECT count(*) FROM expected) || ' tables exist' AS "check",
         CASE WHEN NOT EXISTS (SELECT 1 FROM expected e WHERE to_regclass('public.' || e.t) IS NULL) THEN 'OK'
              ELSE 'PROBLEM: missing ' || (SELECT string_agg(e.t, ', ') FROM expected e WHERE to_regclass('public.' || e.t) IS NULL) END AS status
  UNION ALL SELECT 2, 'Latest columns present',
         CASE WHEN NOT EXISTS (SELECT 1 FROM cols WHERE NOT EXISTS (SELECT 1 FROM information_schema.columns ic WHERE ic.table_schema = 'public' AND ic.table_name = cols.t AND ic.column_name = cols.c)) THEN 'OK' ELSE 'PROBLEM' END
  UNION ALL SELECT 3, 'Row Level Security on every table',
         CASE WHEN NOT EXISTS (SELECT 1 FROM pg_tables WHERE schemaname = 'public' AND NOT rowsecurity) THEN 'OK'
              ELSE 'PROBLEM: ' || (SELECT string_agg(tablename, ', ') FROM pg_tables WHERE schemaname = 'public' AND NOT rowsecurity) END
  UNION ALL SELECT 4, 'Public API roles have no table access',
         CASE WHEN NOT EXISTS (SELECT 1 FROM information_schema.role_table_grants WHERE table_schema = 'public' AND grantee IN ('anon', 'authenticated')) THEN 'OK' ELSE 'PROBLEM' END
  UNION ALL SELECT 5, 'Both setup steps recorded',
         CASE WHEN (SELECT count(*) FROM schema_migrations WHERE name IN (${migrations.map((m) => lit(m)).join(', ')})) = ${migrations.length} THEN 'OK' ELSE 'PROBLEM' END
  UNION ALL SELECT 6, 'Store settings present', CASE WHEN EXISTS (SELECT 1 FROM site_settings WHERE id = 1) THEN 'OK' ELSE 'PROBLEM' END
  UNION ALL SELECT 7, 'Categories present (' || (SELECT count(*) FROM categories) || ')', CASE WHEN (SELECT count(*) FROM categories) >= ${categories.length} THEN 'OK' ELSE 'PROBLEM' END
  UNION ALL SELECT 8, 'Photo bucket product-images is public, 10 MB, JPEG/PNG/WebP only',
         CASE WHEN EXISTS (SELECT 1 FROM storage.buckets WHERE id = 'product-images' AND public AND file_size_limit = ${STORAGE_MAX_BYTES}
                           AND allowed_mime_types @> ${lit([...STORAGE_ALLOWED_TYPES])} AND ${lit([...STORAGE_ALLOWED_TYPES])} @> allowed_mime_types) THEN 'OK' ELSE 'PROBLEM' END
  UNION ALL SELECT 9, 'No upload/delete rules on photo storage (uploads only via the website)',
         CASE WHEN NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'storage' AND tablename = 'objects' AND cmd <> 'SELECT') THEN 'OK'
              ELSE 'CHECK: Storage has write rules: ' || (SELECT string_agg(policyname, ', ') FROM pg_policies WHERE schemaname = 'storage' AND tablename = 'objects' AND cmd <> 'SELECT') END
) checks ORDER BY n;
`)

mkdirSync(join(root, 'supabase'), { recursive: true })
writeFileSync(join(root, 'supabase', 'setup.sql'), parts.join('\n'))

// ── optional sample catalogue
const sample: string[] = [`-- OPTIONAL: 12 illustrated sample products (no photos). Run after setup.sql if you want example products.
-- Delete them later from Admin → Products.
BEGIN;`]
for (const p of seedProducts) {
  const vals = [p.name, p.slug, p.description, p.details, p.price, p.salePrice ?? null, p.colour, p.fabric, p.care, p.fit, p.isFeatured, p.isNewArrival, p.isSoldOut, p.popularity, p.artwork, p.createdAt]
  sample.push(`WITH p AS (
  INSERT INTO products (name, slug, description, details, price, sale_price, category_id, colour, fabric, care, fit, is_featured, is_new_arrival, is_sold_out, popularity, artwork, created_at, updated_at)
  SELECT ${vals.slice(0, 6).map(lit).join(', ')}, c.id, ${vals.slice(6, 15).map(lit).join(', ')}, ${lit(p.createdAt)}::timestamptz, ${lit(p.createdAt)}::timestamptz
  FROM categories c WHERE c.slug = ${lit(p.category)}
  ON CONFLICT (slug) DO NOTHING RETURNING id
), v AS (
  INSERT INTO product_variants (product_id, size) SELECT p.id, s.size FROM p, (VALUES ${Object.keys(p.stock).map((s) => `(${lit(s)})`).join(', ')}) AS s(size) RETURNING id, size
)
INSERT INTO inventory (variant_id, quantity) SELECT v.id, q.qty FROM v JOIN (VALUES ${Object.entries(p.stock).map(([s, n]) => `(${lit(s)}, ${n})`).join(', ')}) AS q(size, qty) ON q.size = v.size;`)
}
sample.push('COMMIT;')
writeFileSync(join(root, 'supabase', 'sample-products.sql'), sample.join('\n\n') + '\n')
console.log('✓ wrote supabase/setup.sql and supabase/sample-products.sql')
